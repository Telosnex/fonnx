/// Writes lib/models/whisper/src/whisper_vocabulary.dart from the Hugging Face
/// `tokenizer.json` and `generation_config.json` of a Whisper model.
///
/// Usage:
///   `dart tool/generate_whisper_vocabulary.dart TOKENIZER_JSON \`
///   `GENERATION_CONFIG_JSON SOURCE_DESCRIPTION`
///
/// The source description goes into the file header, for example
/// `onnx-community/whisper-tiny@ff4177021cc41f7db950912b73ea4fdf7d01d8e7`.
library;

import 'dart:convert';
import 'dart:io';

const _outputPath = 'lib/models/whisper/src/whisper_vocabulary.dart';

const _specialTokens = <String, String>{
  'whisperEndOfText': '<|endoftext|>',
  'whisperStartOfTranscript': '<|startoftranscript|>',
  'whisperEnglish': '<|en|>',
  'whisperTranscribe': '<|transcribe|>',
  'whisperNoTimestamps': '<|notimestamps|>',
};

Future<void> main(List<String> arguments) async {
  if (arguments.length != 3) {
    stderr.writeln(
      'Usage: dart tool/generate_whisper_vocabulary.dart '
      '<tokenizer.json> <generation_config.json> <source description>',
    );
    exitCode = 64;
    return;
  }
  final tokenizer = _object(
    jsonDecode(await File(arguments[0]).readAsString()),
    arguments[0],
  );
  final generation = _object(
    jsonDecode(await File(arguments[1]).readAsString()),
    arguments[1],
  );

  final model = _object(tokenizer['model'], 'model');
  if (model['type'] != 'BPE') throw const FormatException('Not a BPE model');
  final vocabulary = _object(model['vocab'], 'model.vocab');
  final specialIds = <String, int>{};
  for (final raw in tokenizer['added_tokens'] as List<Object?>) {
    final token = _object(raw, 'added_tokens[]');
    specialIds[token['content']! as String] = token['id']! as int;
  }
  final endOfText = specialIds['<|endoftext|>'];
  if (endOfText == null) throw const FormatException('No <|endoftext|>');

  // Text tokens are the IDs below <|endoftext|>. They must be contiguous.
  final pieces = List<String?>.filled(endOfText, null);
  for (final entry in vocabulary.entries) {
    final id = entry.value! as int;
    if (id < endOfText) pieces[id] = entry.key;
  }
  final missing = pieces.indexOf(null);
  if (missing >= 0) {
    throw FormatException('No vocabulary entry for ID $missing');
  }

  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/generate_whisper_vocabulary.dart. Do not edit.',
    )
    ..writeln('// Source: ${arguments[2]}')
    ..writeln('// (tokenizer.json and generation_config.json).')
    ..writeln()
    ..writeln('// Special token IDs.');
  for (final entry in _specialTokens.entries) {
    final id = specialIds[entry.value];
    if (id == null) throw FormatException('No ${entry.value} token');
    out.writeln('const ${entry.key} = $id;');
  }
  out
    ..writeln()
    ..writeln('/// Tokens that Whisper never generates.')
    ..writeln(
      'const whisperSuppressTokens = <int>${_intList(generation['suppress_tokens'])};',
    )
    ..writeln()
    ..writeln(
      '/// Tokens that Whisper never generates as the first text token.',
    )
    ..writeln(
      'const whisperBeginSuppressTokens = '
      '<int>${_intList(generation['begin_suppress_tokens'])};',
    )
    ..writeln()
    ..writeln('/// Byte-level BPE pieces of the text tokens, by token ID.')
    ..writeln('const whisperTextPieces = <String>[');
  for (final piece in pieces) {
    out.writeln('  ${_literal(piece!)},');
  }
  out.writeln('];');
  await File(_outputPath).writeAsString(out.toString());
  final format = await Process.run(Platform.resolvedExecutable, [
    'format',
    _outputPath,
  ]);
  if (format.exitCode != 0) {
    throw ProcessException('dart', ['format', _outputPath], '${format.stderr}');
  }
  stdout.writeln('Wrote $_outputPath: ${pieces.length} text pieces.');
}

Map<String, Object?> _object(Object? value, String name) {
  if (value is Map<String, Object?>) return value;
  throw FormatException('$name is not a JSON object');
}

String _intList(Object? value) {
  if (value is! List || value.any((item) => item is! int)) {
    throw const FormatException('Expected a list of token IDs');
  }
  return '[${value.join(', ')}]';
}

/// A double-quoted Dart literal with only printable ASCII in the source.
String _literal(String value) {
  final out = StringBuffer('"');
  for (final rune in value.runes) {
    if (rune == 0x22 || rune == 0x24 || rune == 0x5C) {
      out.write('\\${String.fromCharCode(rune)}');
    } else if (rune >= 0x20 && rune < 0x7F) {
      out.writeCharCode(rune);
    } else {
      out.write('\\u{${rune.toRadixString(16)}}');
    }
  }
  out.write('"');
  return out.toString();
}
