/// Writes lib/models/nemoAsr/src/nemo_asr_vocabulary.dart from the
/// `tokens.txt` files of the two sherpa-onnx NeMo models.
///
///     dart tool/generate_nemo_asr_vocabulary.dart \
///       <fast-conformer-ctc tokens.txt> <parakeet-tdt-0.6b-v3 tokens.txt>
///
/// Each line of tokens.txt is a token and its ID. The IDs are 0, 1, 2, ...
/// and the last token is the blank, `<blk>`.
library;

import 'dart:io';

Future<void> main(List<String> args) async {
  if (args.length != 2) {
    stderr.writeln(
      'usage: dart tool/generate_nemo_asr_vocabulary.dart '
      '<ctc tokens.txt> <tdt tokens.txt>',
    );
    exit(64);
  }
  final ctc = await _read(args[0]);
  final tdt = await _read(args[1]);
  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/generate_nemo_asr_vocabulary.dart. '
      'Do not edit.',
    )
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln(
      '/// Tokens of the multilingual FastConformer CTC model, by ID. '
      'The last one',
    )
    ..writeln('/// is the blank.')
    ..write(_list('nemoCtcMultilingualTokens', ctc))
    ..writeln()
    ..writeln(
      '/// Tokens of Parakeet TDT 0.6B v3, by ID. The last one is the '
      'blank.',
    )
    ..write(_list('parakeetTdtV3Tokens', tdt));
  await File(
    'lib/models/nemoAsr/src/nemo_asr_vocabulary.dart',
  ).writeAsString(out.toString());
}

Future<List<String>> _read(String path) async {
  final tokens = <String>[];
  for (final line in await File(path).readAsLines()) {
    if (line.isEmpty) {
      continue;
    }
    final space = line.lastIndexOf(' ');
    final id = int.parse(line.substring(space + 1));
    if (id != tokens.length) {
      throw FormatException('$path: ID $id out of order');
    }
    tokens.add(line.substring(0, space));
  }
  if (tokens.last != '<blk>') {
    throw FormatException('$path: no final <blk>');
  }
  return tokens;
}

String _list(String name, List<String> tokens) {
  final out = StringBuffer('const $name = <String>[\n');
  for (final token in tokens) {
    out.writeln('  ${_literal(token)},');
  }
  return (out..writeln('];')).toString();
}

String _literal(String s) {
  final out = StringBuffer("'");
  for (final rune in s.runes) {
    if (rune == 0x27 || rune == 0x5C || rune == 0x24) {
      out.write('\\${String.fromCharCode(rune)}');
    } else if (rune < 0x20 || rune == 0x7F || (rune >= 0x80 && rune < 0xA0)) {
      out.write('\\u{${rune.toRadixString(16)}}');
    } else {
      out.writeCharCode(rune);
    }
  }
  return (out..write("'")).toString();
}
